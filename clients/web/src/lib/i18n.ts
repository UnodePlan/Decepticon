export const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, zh };

export type TranslationParams = Record<string, string | number>;

/**
 * Resolve any raw locale-ish value (env var, cookie, `navigator.language`)
 * to a supported locale. `zh-CN`, `zh_TW` and `zh-Hans` all map to `zh`.
 */
export function normalizeLocale(value: string | null | undefined): Locale {
  if (!value) return DEFAULT_LOCALE;
  const primary = value.trim().toLowerCase().split(/[-_]/)[0];
  return (LOCALES as readonly string[]).includes(primary) ? (primary as Locale) : DEFAULT_LOCALE;
}

export function hasTranslation(locale: Locale, key: string): boolean {
  return key in dictionaries[locale] || key in dictionaries[DEFAULT_LOCALE];
}

function interpolate(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match
  );
}

/**
 * Look up `key`, falling back to English and finally to the key itself so a
 * missing entry degrades visibly instead of rendering "undefined".
 */
export function translate(locale: Locale, key: string, params?: TranslationParams): string {
  const localized = dictionaries[locale] as Record<string, string | undefined>;
  const template = localized[key] ?? (dictionaries[DEFAULT_LOCALE] as Record<string, string>)[key] ?? key;
  return interpolate(template, params);
}

/** Severity label for an API value; unknown values pass through unchanged. */
export function severityLabel(locale: Locale, severity: string): string {
  const key = `severity.${severity.toLowerCase()}`;
  return hasTranslation(locale, key) ? translate(locale, key) : severity;
}

/** Engagement status label for an API value; unknown values pass through. */
export function statusLabel(locale: Locale, status: string): string {
  const key = `status.${status.toLowerCase()}`;
  return hasTranslation(locale, key) ? translate(locale, key) : status;
}
